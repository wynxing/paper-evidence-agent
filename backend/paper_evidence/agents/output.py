"""Parse and validate paper-agent output.

Structure and per-step action legality are checked with Pydantic. Quote validity
is checked deterministically against the frozen paragraph text in the workflow,
not here. A malformed response is MODEL_INVALID_OUTPUT; a response whose quotes
cannot be located is QUOTE_MISMATCH. Both are repairable once globally.

A rejected response names every field that broke the contract, because this text
is both the operator's diagnosis and the input to the one repair request: a
message that only said "动作字段不合法" could not tell a malformed ``decision``
from a malformed ``action`` (Issue #62).

Every branch hands the **whole** payload to its contract, ``action`` included, so
a field outside the contract is rejected at the top level exactly as it is inside
``decision``. Hand-picking the keys a branch happens to know makes ``extra="forbid"``
a rule with an undocumented exception: ``final`` used to pass only ``decision``,
so a stray top-level field was dropped before validation ever saw it, while the
same stray field made ``retrieve`` fail (Issue #79).
"""

import json
import re

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from paper_evidence.domain.contracts import AcademicLabel

__all__ = [
    "EvidenceDraft",
    "DecisionDraft",
    "FinalAction",
    "OutputError",
    "RetrieveAction",
    "parse_decision_output",
    "parse_query_output",
]

_FENCE = re.compile(r"```(?:json)?\s*(.*?)```", re.DOTALL)


class OutputError(ValueError):
    """A structurally invalid model response."""


class _Contract(BaseModel):
    """Reject fields outside the contract, at the top level and nested alike.

    ``extra="forbid"`` only means anything when the **whole** payload reaches it:
    a parser that pre-filters the keys it knows hides the stray ones from this
    setting, and then whether a field is rejected depends on how the call site was
    written rather than on the contract (Issue #79).
    """

    model_config = ConfigDict(extra="forbid")


class EvidenceDraft(_Contract):
    """Only the paragraph id and the verbatim quote come from the model.

    Section, source_url and paragraph_hash are filled deterministically from the
    frozen paragraph, because bibliographic and section fields may not be
    generated by the model.
    """

    paragraph_id: str
    quote: str


class DecisionDraft(_Contract):
    label: AcademicLabel
    rationale: str
    supported_parts: list[str] = Field(default_factory=list)
    scope_differences: list[str] = Field(default_factory=list)
    limitations: list[str] = Field(default_factory=list)
    evidence: list[EvidenceDraft] = Field(default_factory=list)


class RetrieveAction(_Contract):
    """A legal retrieve supplies at least one query or one known neighbour id.

    This is per-step action legality (架构设计「动作与预算」), so a violating
    response is MODEL_INVALID_OUTPUT and repairable, not a retrieval failure.
    Whether the first empty round additionally demands non-empty queries is
    context-dependent and is checked by the workflow.
    """

    action: str = "retrieve"
    queries: list[str] = Field(default_factory=list)
    neighbor_paragraph_ids: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _require_a_target(self) -> "RetrieveAction":
        if any(not item.strip() for item in self.queries):
            raise ValueError("queries 含空白项")
        if not any(item.strip() for item in self.queries) and not self.neighbor_paragraph_ids:
            raise ValueError("retrieve 至少需要一个非空 queries 或已知 neighbor_paragraph_ids")
        return self


class FinalAction(_Contract):
    action: str = "final"
    decision: DecisionDraft


def _extract_json(text: str) -> dict:
    candidates = _FENCE.findall(text)
    for candidate in [*candidates, text]:
        stripped = candidate.strip()
        start = stripped.find("{")
        if start == -1:
            continue
        try:
            value = json.loads(stripped[start:])
        except ValueError:
            continue
        if isinstance(value, dict):
            return value
    raise OutputError("模型输出不是 JSON 对象")


#: pydantic 错误类型 → 该字段期望什么。未登记的类型直接用 pydantic 自己的说明，
#: 不猜一个中文说法：这条消息同时是人看的诊断和修复提示词的输入，不许失真。
_EXPECTED = {
    "list_type": "字符串数组",
    "string_type": "字符串",
    "dict_type": "对象",
    "model_type": "对象",
    "literal_error": "四类学术标签之一",
}

#: 收到的值只报类型。原值可能是整段模型输出，既不进日志，也不该塞进修复提示词。
_RECEIVED = {str: "字符串", list: "数组", dict: "对象", bool: "布尔值", int: "数字", float: "数字"}


def _received(value: object) -> str:
    for kind, name in _RECEIVED.items():
        if type(value) is kind:
            return name
    return "空值" if value is None else type(value).__name__


def _failure(action: str, item: dict) -> str:
    """One field-level failure, prefixed with the action whose payload failed.

    ``action`` is the branch that was validated, not a field: putting it in the
    path keeps a malformed ``decision`` from reading like a malformed ``action``
    (Issue #62).
    """

    path = ".".join([action, *(str(step) for step in item["loc"])])
    if item["type"] == "missing":
        return f"{path}: missing（缺少必填字段）"
    if item["type"] == "extra_forbidden":
        return f"{path}: extra_forbidden（契约外的多余字段）"
    expected = _EXPECTED.get(item["type"])
    if expected is None:
        return f"{path}: {item['type']}（{item['msg'].removeprefix('Value error, ')}）"
    return f"{path}: {item['type']}（需要{expected}，收到{_received(item.get('input'))}）"


def _diagnosis(action: str, error: ValidationError) -> str:
    """Every field failure of this response, not one sentence about ``action``.

    测试方案「任务内澄清、隔离与多步执行」要求一次修复的输入包含当前响应**全部**可
    检测错误；旧实现把所有 ``ValidationError`` 折成「动作字段不合法」，既漏掉出错的
    字段，也把方向指到了 ``action`` 上，修复提示词因此无法纠正（Issue #62）。
    """

    return "；".join(_failure(action, item) for item in error.errors())


def parse_query_output(text: str) -> list[str]:
    payload = _extract_json(text)
    queries = payload.get("queries")
    if not isinstance(queries, list) or not queries:
        raise OutputError("queries 必须是非空字符串数组")
    if not all(isinstance(item, str) and item.strip() for item in queries):
        raise OutputError("queries 含空白或非字符串项")
    return [item for item in queries]


def parse_decision_output(text: str) -> RetrieveAction | FinalAction:
    payload = _extract_json(text)
    action = payload.get("action")
    try:
        # 两个分支送同一份东西：整份载荷。`action` 本来就是两个动作各自的字段，
        # 而只挑契约内键送校验会让 final 的顶层多余字段在校验前被丢掉、retrieve 的
        # 同一类输入却报错——同一份 `_Contract` 出两种严格度（Issue #79）。
        if action == "retrieve":
            return RetrieveAction.model_validate(payload)
        if action == "final":
            return FinalAction.model_validate(payload)
    except ValidationError as error:
        raise OutputError(_diagnosis(action, error)) from error
    raise OutputError("未知的 action")
